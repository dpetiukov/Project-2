// 1. Запросіть у користувача його вік та визначіть, ким він є: дитиною (0–12), 
// підлітком (12–18), дорослим (18–60) або пенсіонером (60– …).
const age = prompt("Введіть Ваш вік: ");

if (age >=0 && age <= 12) {
  alert("Ви є дитиною.");
}
else if (age > 12 && age <= 18) {
  alert("Ви є підлітком.");
}
else if (age >=18 && age <= 60) {
  alert("Ви є дорослим.");
}
else if (age >= 60) {
  alert("Ви є пенсіонером.");
}